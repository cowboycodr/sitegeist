#!/usr/bin/env node

import { cp, mkdir, readFile, rename, rm } from 'node:fs/promises';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	atomicWrite,
	copyOptionalFile,
	parseCli,
	pathExists,
	requireOption,
	validateSubmission
} from './lib/artifacts.mjs';

const START_MARKER = '/* SITEGEIST_REGISTRY_JSON_START */';
const END_MARKER = '/* SITEGEIST_REGISTRY_JSON_END */';
const usage = `Usage:
  node scripts/benchmark/import-site.mjs --submission <directory> --registry <file.json|file.ts>
      [--static-root <directory>] [--public-base </sites/model>] [--replace]

Validates one submission, copies its dist/ to static/sites/<artifactDirectory>/,
copies the authored gallery preview and canonical audit captures, and adds the
artifact to the generated registry.
--static-root defaults to this repository's static/sites directory.
--public-base defaults to /sites and must match the static root's public URL.`;

function normalizePublicBase(value = '/sites') {
	if (
		typeof value !== 'string' ||
		!value.startsWith('/') ||
		value.includes('\\') ||
		value.includes('?') ||
		value.includes('#') ||
		value.split('/').includes('..')
	) {
		throw new Error('--public-base must be an absolute URL path without traversal, query, or fragment');
	}
	return value === '/' ? '' : value.replace(/\/+$/, '');
}

function assertRegistryRecord(record, source) {
	const migrated = record && typeof record === 'object'
		? {
			...record,
			tagline: record.tagline ?? record.title,
			description: record.description ?? record.tagline ?? record.title,
			posterUrl: record.posterUrl ?? record.desktopPreviewUrl,
			desktopAuditUrl:
				record.desktopAuditUrl !== undefined
					? record.desktopAuditUrl
					: (record.desktopPreviewUrl ?? null),
			mobileAuditUrl:
				record.mobileAuditUrl !== undefined
					? record.mobileAuditUrl
					: (record.mobilePreviewUrl ?? null)
		}
		: record;
	const keys = [
		'slug',
		'title',
		'category',
		'tagline',
		'description',
		'artifactUrl',
		'posterUrl',
		'sourceHash',
		'distHash'
	];
	if (!migrated || typeof migrated !== 'object' || !Number.isSafeInteger(migrated.id)) {
		throw new Error(`${source} contains an invalid registry record`);
	}
	for (const key of keys) {
		if (typeof migrated[key] !== 'string') {
			throw new Error(`${source} record ${migrated.id} has invalid ${key}`);
		}
	}
	for (const key of ['desktopAuditUrl', 'mobileAuditUrl']) {
		if (migrated[key] !== null && typeof migrated[key] !== 'string') {
			throw new Error(`${source} record ${migrated.id} has invalid ${key}`);
		}
	}
	return {
		id: migrated.id,
		slug: migrated.slug,
		title: migrated.title,
		category: migrated.category,
		tagline: migrated.tagline,
		description: migrated.description,
		artifactUrl: migrated.artifactUrl,
		posterUrl: migrated.posterUrl,
		desktopAuditUrl: migrated.desktopAuditUrl,
		mobileAuditUrl: migrated.mobileAuditUrl,
		sourceHash: migrated.sourceHash,
		distHash: migrated.distHash
	};
}

async function readRegistry(registryPath) {
	let contents;
	try {
		contents = await readFile(registryPath, 'utf8');
	} catch (error) {
		if (error?.code === 'ENOENT') return [];
		throw error;
	}

	const extension = extname(registryPath);
	let records;
	if (extension === '.json') {
		records = JSON.parse(contents);
	} else if (extension === '.ts') {
		const start = contents.indexOf(START_MARKER);
		const end = contents.indexOf(END_MARKER);
		if (start !== -1 && end !== -1 && end > start) {
			records = JSON.parse(contents.slice(start + START_MARKER.length, end).trim());
		} else {
			const legacyArray = contents.match(
				/export const siteArtifacts\s*:\s*SiteArtifact\[\]\s*=\s*(\[[\s\S]*?\])\s*;/
			);
			if (!legacyArray) {
				throw new Error(`${registryPath} is not a generated Sitegeist registry`);
			}
			records = JSON.parse(legacyArray[1]);
		}
	} else {
		throw new Error('--registry must end in .json or .ts');
	}

	if (!Array.isArray(records)) throw new Error(`${registryPath} must contain a registry array`);
	return records.map((record) => assertRegistryRecord(record, registryPath));
}

function renderRegistry(records, extension) {
	const json = JSON.stringify(records, null, '\t');
	if (extension === '.json') return `${json}\n`;
	if (extension !== '.ts') throw new Error('--registry must end in .json or .ts');

	return `// Generated by scripts/benchmark/import-site.mjs. Do not edit by hand.\n\nexport type SiteArtifact = {\n\tid: number;\n\tslug: string;\n\ttitle: string;\n\tcategory: string;\n\ttagline: string;\n\tdescription: string;\n\tartifactUrl: string;\n\tposterUrl: string;\n\tdesktopAuditUrl: string | null;\n\tmobileAuditUrl: string | null;\n\tsourceHash: string;\n\tdistHash: string;\n};\n\nexport const siteArtifacts: SiteArtifact[] =\n${START_MARKER}\n${json}\n${END_MARKER};\n\nexport const siteArtifactBySlug = new Map(\n\tsiteArtifacts.map((artifact) => [artifact.slug, artifact])\n);\n`;
}

async function installArtifact(validated, staticRoot, replace) {
	const destination = join(staticRoot, validated.manifest.artifactDirectory);
	const staging = join(staticRoot, `.sitegeist-import-${process.pid}-${Date.now()}`);
	const backup = join(staticRoot, `.sitegeist-backup-${process.pid}-${Date.now()}`);
	const destinationExists = await pathExists(destination);
	if (destinationExists && !replace) {
		throw new Error(`Artifact already exists (use --replace to update it): ${destination}`);
	}

	await mkdir(staticRoot, { recursive: true });
	try {
		await cp(validated.distDirectory, staging, {
			recursive: true,
			errorOnExist: true,
			force: false
		});
		await cp(validated.previewDirectory, join(staging, '_preview'), {
			recursive: true,
			errorOnExist: true,
			force: false
		});
		await copyOptionalFile(
			validated.auditPaths.desktop,
			join(staging, '_audit', 'desktop.webp')
		);
		await copyOptionalFile(
			validated.auditPaths.mobile,
			join(staging, '_audit', 'mobile.webp')
		);
		if (destinationExists) {
			await rename(destination, backup);
		}
		try {
			await rename(staging, destination);
		} catch (error) {
			if (destinationExists && (await pathExists(backup))) {
				await rename(backup, destination);
			}
			throw error;
		}
		await rm(backup, { recursive: true, force: true });
		return destination;
	} finally {
		await rm(staging, { recursive: true, force: true });
	}
}

async function main() {
	const options = parseCli(
		process.argv.slice(2),
		new Set(['submission', 'registry', 'static-root', 'public-base']),
		new Set(['help', 'replace'])
	);
	if (options.help) {
		console.log(usage);
		return;
	}
	if (options._.length > 0) throw new Error(`Unexpected argument: ${options._[0]}`);

	const submission = resolve(requireOption(options, 'submission'));
	const registry = resolve(requireOption(options, 'registry'));
	const scriptDirectory = dirname(fileURLToPath(import.meta.url));
	const staticRoot = resolve(options['static-root'] ?? join(scriptDirectory, '../../static/sites'));
	const publicBase = normalizePublicBase(options['public-base']);
	const replace = Boolean(options.replace);
	const validated = await validateSubmission(submission);
	const directory = validated.manifest.artifactDirectory;
	const baseUrl = `${publicBase}/${directory}`;
	const record = {
		id: validated.manifest.id,
		slug: validated.manifest.slug,
		title: validated.manifest.title,
		category: validated.manifest.category,
		tagline: validated.manifest.tagline,
		description: validated.manifest.description,
		artifactUrl: `${baseUrl}/index.html`,
		posterUrl: `${baseUrl}/_preview/poster.svg`,
		desktopAuditUrl: validated.audit.desktop ? `${baseUrl}/_audit/desktop.webp` : null,
		mobileAuditUrl: validated.audit.mobile ? `${baseUrl}/_audit/mobile.webp` : null,
		sourceHash: validated.source.hash,
		distHash: validated.dist.hash
	};

	const records = await readRegistry(registry);
	const existingIndex = records.findIndex((candidate) => candidate.slug === record.slug);
	if (existingIndex !== -1 && !replace) {
		throw new Error(`Registry already contains ${record.slug} (use --replace to update it)`);
	}
	if (existingIndex !== -1 && records[existingIndex].artifactUrl !== record.artifactUrl) {
		throw new Error('Changing artifactDirectory during --replace is not supported');
	}
	const idCollision = records.find(
		(candidate) => candidate.id === record.id && candidate.slug !== record.slug
	);
	if (idCollision) throw new Error(`Registry id ${record.id} is already used by ${idCollision.slug}`);
	const urlCollision = records.find(
		(candidate) => candidate.artifactUrl === record.artifactUrl && candidate.slug !== record.slug
	);
	if (urlCollision) {
		throw new Error(`Artifact directory is already used by ${urlCollision.slug}`);
	}

	if (existingIndex === -1) records.push(record);
	else records[existingIndex] = record;
	records.sort((a, b) => a.id - b.id || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

	const destination = await installArtifact(validated, staticRoot, replace);
	await atomicWrite(registry, renderRegistry(records, extname(registry)));

	console.log(
		JSON.stringify(
			{
				record,
				destination,
				registry,
				previewPresent: validated.preview,
				auditCapturesPresent: validated.audit
			},
			null,
			2
		)
	);
}

main().catch((error) => {
	console.error(`import-site: ${error.message}`);
	process.exitCode = 1;
});
